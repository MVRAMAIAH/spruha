/**
 * Get constituency by ID
 */
export const getConstituencyById = (id) =>
  CONSTITUENCIES.find(c => c.id === id);

/**
 * Get all constituencies in a district
 */
export const getConstituenciesByDistrict = (districtId) =>
  CONSTITUENCIES.filter(c => c.districtId === districtId);

/**
 * Search constituencies by name
 */
export const searchConstituencies = (query) => {
  const lower = query.toLowerCase();
  return CONSTITUENCIES.filter(c =>
    c.name.toLowerCase().includes(lower)
  );
};

/**
 * Get all constituencies except the specified one
 */
export const getOtherConstituencies = (excludeId) =>
  CONSTITUENCIES.filter(c => c.id !== excludeId);
